// Regenerates the printer compatibility table in README.md from the code
// (src/printers/models.js, src/compat.js and the label catalogue).
//
//   npm run docs
//
// test/readme.test.js fails when README.md is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODELS } from '../src/printers/models.js';
import { applyCatalog } from '../src/catalog.js';
import { compatMarkdown } from '../src/compat.js';

export const START = '<!-- compat:start: generated by `npm run docs` from src/printers/models.js and src/compat.js; do not edit by hand -->';
export const END = '<!-- compat:end -->';

const README = new URL('../README.md', import.meta.url);
const CATALOG = new URL('../catalog/media.rec', import.meta.url);

export function renderReadme(readme) {
  const models = applyCatalog(readFileSync(CATALOG, 'utf8'), Object.fromEntries(Object.entries(MODELS).map(([id, m]) => [id, { ...m }])));
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) throw new Error('README.md is missing the compat:start / compat:end markers');
  return `${readme.slice(0, start + START.length)}\n${compatMarkdown(models)}\n${readme.slice(end)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = readFileSync(README, 'utf8');
  const after = renderReadme(before);
  writeFileSync(README, after);
  console.log(before === after ? 'README.md already up to date' : 'README.md compatibility table updated');
}
