// Regenerates the generated sections of README.md from the code: the
// printer compatibility table (src/printers/models.js, src/compat.js and the
// label catalogue), who it's for and the list of other tools (src/others.js), and the credits
// (src/credits.js).
//
//   npm run docs
//
// test/readme.test.js fails when README.md is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODELS } from '../src/printers/models.js';
import { applyCatalog, applyPrinters } from '../src/catalog.js';
import { compatMarkdown } from '../src/compat.js';
import { othersMarkdown, aimsMarkdown } from '../src/others.js';
import { creditsMarkdown } from '../src/credits.js';
import { appFiles } from './app-files.mjs';

export const START = '<!-- compat:start: generated by `npm run docs` from src/printers/models.js and src/compat.js; do not edit by hand -->';
export const END = '<!-- compat:end -->';
const OTHERS_START = '<!-- others:start: generated by `npm run docs` from src/others.js; do not edit by hand -->';
const OTHERS_END = '<!-- others:end -->';
const AIMS_START = '<!-- aims:start: generated by `npm run docs` from src/others.js; do not edit by hand -->';
const AIMS_END = '<!-- aims:end -->';
const CREDITS_START = '<!-- credits:start: generated by `npm run docs` from src/credits.js; do not edit by hand -->';
const CREDITS_END = '<!-- credits:end -->';

function replaceSection(text, start, end, body) {
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`README.md is missing the ${start.slice(5, 20)}… / ${end} markers`);
  return `${text.slice(0, a + start.length)}\n${body}\n${text.slice(b)}`;
}

const README = new URL('../README.md', import.meta.url);
const SW = new URL('../sw.js', import.meta.url);
const SW_START = '// app-files:start: generated by `npm run docs`; do not edit by hand';
const SW_END = '// app-files:end';

// sw.js with the list of files it caches, from the files on disk (minus
// sw.js itself, which the browser keeps).
export function renderSw(sw) {
  const files = appFiles().filter((f) => f !== 'sw.js');
  return replaceSection(sw, SW_START, SW_END, `const FILES = [\n${files.map((f) => `  '${f}',`).join('\n')}\n];`);
}
const CATALOG = new URL('../catalog/media.rec', import.meta.url);
const PRINTERS = new URL('../catalog/printers.rec', import.meta.url);

// docs/PRINT-SERVER-API.md: the printer ids a print server can name.
const API_DOC = new URL('../docs/PRINT-SERVER-API.md', import.meta.url);
const IDS_START = '<!-- model-ids:start: generated by `npm run docs` from src/printers/models.js and catalog/; do not edit by hand -->';
const IDS_END = '<!-- model-ids:end -->';
export function renderApiDoc(doc) {
  const models = applyPrinters(readFileSync(PRINTERS, 'utf8'),
    applyCatalog(readFileSync(CATALOG, 'utf8'), Object.fromEntries(Object.entries(MODELS).map(([id, m]) => [id, { ...m }]))));
  const rows = Object.entries(models).filter(([id]) => id !== 'generic').map(([id, m]) => {
    const media = m.media.map((x) => `\`${x.id}\``);
    const shown = media.length > 6 ? `${media.slice(0, 6).join(', ')} … (${media.length})` : media.join(', ');
    return `| \`${id}\` | ${m.name} | ${m.protocol ?? ''} | ${shown} |`;
  });
  return replaceSection(doc, IDS_START, IDS_END,
    ['| `model` | Printer | Protocol | `medium` ids (catalog/media.rec) |', '|---|---|---|---|', ...rows].join('\n'));
}

export function renderReadme(readme) {
  const models = applyPrinters(readFileSync(PRINTERS, 'utf8'),
    applyCatalog(readFileSync(CATALOG, 'utf8'), Object.fromEntries(Object.entries(MODELS).map(([id, m]) => [id, { ...m }]))));
  const withTable = replaceSection(readme, START, END, compatMarkdown(models));
  const withOthers = replaceSection(withTable, OTHERS_START, OTHERS_END, othersMarkdown());
  const withAims = replaceSection(withOthers, AIMS_START, AIMS_END, aimsMarkdown());
  return replaceSection(withAims, CREDITS_START, CREDITS_END, creditsMarkdown());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const before = readFileSync(README, 'utf8');
  const after = renderReadme(before);
  writeFileSync(README, after);
  console.log(before === after ? 'README.md already up to date' : 'README.md generated sections updated');
  const sw = readFileSync(SW, 'utf8');
  writeFileSync(SW, renderSw(sw));
  writeFileSync(API_DOC, renderApiDoc(readFileSync(API_DOC, 'utf8')));
  if (renderSw(sw) !== sw) console.log('sw.js file list updated');
}
